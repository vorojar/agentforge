const messages: Record<Locale, TranslationTable> = { zh, ja, en };

export const localeOptions: Array<{ value: Locale; labelKey: MessageKey }> = [
  { value: "zh", labelKey: "common.chinese" },
  { value: "ja", labelKey: "common.japanese" },
  { value: "en", labelKey: "common.english" },
];

function isLocale(value: string | null): value is Locale {
  return value === "zh" || value === "ja" || value === "en";
}

function detectInitialLocale(): Locale {
  const stored = localStorage.getItem(storageKey);
  if (isLocale(stored)) return stored;

  const language = navigator.language.toLowerCase();
  if (language.startsWith("ja")) return "ja";
  if (language.startsWith("zh")) return "zh";
  return "en";
}

export const locale = ref<Locale>(detectInitialLocale());

export function setLocale(nextLocale: Locale) {
  locale.value = nextLocale;
  localStorage.setItem(storageKey, nextLocale);
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  let message = messages[locale.value][key] ?? en[key] ?? key;
  if (!vars) return message;

  for (const [name, value] of Object.entries(vars)) {
    message = message.replaceAll(`{${name}}`, String(value));
  }
  return message;
}
